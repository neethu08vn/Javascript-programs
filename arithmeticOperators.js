var a = 10
var b = 5
console.log(a+b) //addition
console.log(a-b) //subtraction
console.log(a*b) //multiplication
console.log(a/b) //division
console.log(a%b) //modulus
console.log(a**b) //exponentiation
console.log(a--) //decrement
console.log(b++) //increment
console.log(a) //printing the value of a after decrement
console.log(b) //printing the value of b after increment
console.log(--a) //pre decrement
console.log(++b) //pre increment
console.log(a) //printing the value of a after pre decrement
console.log(b) //printing the value of b after pre increment

